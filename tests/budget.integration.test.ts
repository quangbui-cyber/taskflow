import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import type { FinanceData } from "../lib/costflow/types";
import { currentPurchaseOrders } from "../lib/costflow/budgetSources";
import { calculateCost } from "../lib/costflow/money";

test("Budget sources persist immutable versions, reject foreign/stale actors and serialize competing successors", async () => {
  const url = new URL(process.env.COSTFLOW_TEST_DATABASE_URL ?? "http://invalid");
  assert.ok(["localhost", "127.0.0.1"].includes(url.hostname) && url.pathname === "/costflow_test");
  process.env.DATABASE_URL = url.href;
  const { prisma } = await import("../lib/prisma");
  const { executeFinance } = await import("../lib/costflow/service");
  const prefix = `budget-${randomUUID()}`;
  const account = await prisma.user.create({ data: { email: `${prefix}@example.test`, name: "Budget Account", role: "ACCOUNT", passwordHash: "unused" } });
  const reader = await prisma.user.create({ data: { email: `${prefix}-reader@example.test`, name: "Reader", role: "USER", passwordHash: "unused" } });
  const project = await prisma.project.create({ data: { name: prefix, ownerId: account.id, revenue: 777, members: { create: [{ userId: account.id }, { userId: reader.id }] } } });
  const other = await prisma.project.create({ data: { name: `${prefix}-other`, ownerId: account.id } });
  try {
    const proof = await prisma.projectFile.create({ data: { projectId: project.id, name: "original.txt", mimeType: "text/plain", size: 8, data: Buffer.from("original") } });
    const foreign = await prisma.projectFile.create({ data: { projectId: other.id, name: "foreign.txt", mimeType: "text/plain", size: 7, data: Buffer.from("foreign") } });
    const state = async () => (await prisma.costFlowWorkspace.findUniqueOrThrow({ where: { projectId: project.id } })).data as unknown as FinanceData;
    const version = async () => (await prisma.costFlowWorkspace.findUnique({ where: { projectId: project.id } }))?.version ?? 0;
    const act = async (command: string, fields: Record<string, string | string[]> = {}, actor = account, expected?: number) => {
      const form = new FormData(); form.set("command", command);
      for (const [key, value] of Object.entries(fields)) for (const item of Array.isArray(value) ? value : [value]) form.append(key, item);
      if (command === "DECIDE" && typeof fields.requestId === "string") {
        const request = await prisma.workflowRequest.findUniqueOrThrow({ where: { id: fields.requestId } });
        const submitted = await prisma.workflowApprovalEvent.findFirst({ where: { requestId: request.id, attemptId: request.currentAttemptId, action: "SUBMIT" }, orderBy: { createdAt: "desc" } });
        form.set("module", request.module); form.set("attemptId", request.currentAttemptId ?? "");
        form.set("stepIndex", String(request.currentStep)); form.set("submittedVersion", String(submitted?.submittedVersion ?? ""));
        if (fields.decision === "APPROVE") form.set("reviewConfirmed", "yes");
      }
      return executeFinance(project.id, expected ?? await version(), actor, form, null);
    };
    await act("ADD_PO", { poNumber: "A", net: "100", sourceFileId: proof.id, confirmed: "yes" });
    const original = (await state()).pos[0];
    const evidence = await prisma.costFlowEvidence.findUniqueOrThrow({ where: { id: original.sourceId } });
    await assert.rejects(act("REVISE_PO", { predecessorId: original.id, poNumber: "A", net: "120", sourceFileId: foreign.id, confirmed: "yes" }));
    await assert.rejects(act("REVISE_PO", { predecessorId: original.id, poNumber: "A", net: "120", sourceFileId: proof.id, confirmed: "yes" }, reader));
    const v = await version();
    const race = await Promise.allSettled([act("REVISE_PO", { predecessorId: original.id, poNumber: "A", net: "120", sourceFileId: proof.id, confirmed: "yes" }, account, v), act("REVISE_PO", { predecessorId: original.id, poNumber: "A", net: "130", sourceFileId: proof.id, confirmed: "yes" }, account, v)]);
    assert.equal(race.filter(r => r.status === "fulfilled").length, 1);
    const revised = currentPurchaseOrders((await state()).pos)[0];
    assert.ok(["120", "130"].includes(revised.net));
    await assert.rejects(act("REVISE_PO", { predecessorId: original.id, poNumber: "A", net: "140", sourceFileId: proof.id, confirmed: "yes" }));
    await act("REPLACE_PO", { predecessorId: revised.id, poNumber: "B", net: "150", sourceFileId: proof.id, confirmed: "yes" });
    assert.equal(currentPurchaseOrders((await state()).pos)[0].net, "150");
    assert.deepEqual((await state()).pos[0], original);
    assert.equal((await prisma.costFlowEvidence.findUniqueOrThrow({ where: { id: evidence.id } })).sha256, evidence.sha256);
    assert.equal(await prisma.costFlowEvidence.count({ where: { projectId: project.id } }), 3);
    assert.equal((await prisma.project.findUniqueOrThrow({ where: { id: project.id } })).revenue, 777);
    assert.equal(await prisma.costFlowCash.count({ where: { projectId: project.id } }), 0);
    const createVersion = await version();
    const draftRace = await Promise.allSettled(["Incomplete IC", "Competing IC"].map(title => act("SAVE_IC", { title, lines: JSON.stringify([{ evidenceReason: "Synthetic test estimate pending supplier document", description: "Print", unit: "set", quantity: "3", days: "1", unitPrice: "", basis: "NET", vatPercent: "" }]) }, account, createVersion)));
    assert.equal(draftRace.filter(result => result.status === "fulfilled").length, 1);
    assert.equal((await state()).revisions.length, 1);
    const draft = (await state()).revisions[0];
    assert.equal(draft.lines[0].cost, null);
    assert.equal(draft.lines[0].unitPrice, "");
    assert.equal(draft.lines[0].vatPercent, "");
    await assert.rejects(act("SUBMIT", { requestId: draft.requestId, explanation: "Incomplete draft" }), /đủ nội dung/);
    await assert.rejects(act("SAVE_IC", { requestId: draft.requestId, title: "Invalid", lines: JSON.stringify([{ ...draft.lines[0], unitPrice: "bad" }]) }));
    await act("SAVE_IC", { requestId: draft.requestId, title: "Filled", lines: JSON.stringify([{ ...draft.lines[0], unitPrice: "100.4", vatPercent: "0", evidenceIds: [evidence.id] }]) });
    assert.equal((await state()).revisions[0].lines[0].cost?.net, "301");
    await assert.rejects(act("COPY_IC", { sourceRevisionId: randomUUID(), title: "Foreign copy" }), /cùng project/);
    await assert.rejects(act("COPY_IC", { sourceRevisionId: draft.id, title: "Competing" }), /đang xử lý/);
    await prisma.user.update({ where: { id: account.id }, data: { managerId: account.id } });
    const configured = await state(); configured.config = { managerId: account.id, accountantId: account.id, ceoId: account.id };
    await prisma.costFlowWorkspace.update({ where: { projectId: project.id }, data: { data: JSON.parse(JSON.stringify(configured)) } });
    await act("SUBMIT", { requestId: draft.requestId, explanation: "Initial budget submission" });
    const sent = await prisma.workflowRequest.findUniqueOrThrow({ where: { id: draft.requestId } });
    await act("DECIDE", { requestId: draft.requestId, decision: "APPROVE" });
    assert.equal((await state()).revisions[0].effective, true);
    // Historical fixtures exercise conservation only; creating them grants no payment authorization.
    const paidLine = (await state()).revisions[0].lines[0];
    const historicalInput = { quantity: "1", unitPrice: "10", basis: "NET" as const, vatPercent: "0" };
    const historicalExpense = { id: randomUUID(), revisionId: draft.id, lineId: paidLine.id, recipientKey: `USER:${account.id}`, description: "Historical AC", input: historicalInput, cost: calculateCost(historicalInput), invoiceId: evidence.id, paymentProofId: evidence.id, createdBy: account.id };
    const historicalState = await state(); historicalState.expenses.push(historicalExpense);
    await prisma.costFlowWorkspace.update({ where: { projectId: project.id }, data: { data: JSON.parse(JSON.stringify(historicalState)) } });
    const paymentRequest = await prisma.workflowRequest.create({ data: { projectId: project.id, module: "COSTFLOW", kind: "PAYMENT", title: "Historical payment fixture", creatorId: account.id, cashAssigneeId: account.id, state: "APPROVED", steps: [], payload: { revisionId: draft.id, expenseIds: [historicalExpense.id] } } });
    const historicalCash = await prisma.costFlowCash.create({ data: { projectId: project.id, requestId: paymentRequest.id, recipientKey: historicalExpense.recipientKey, direction: "OUT", amount: "10", reference: `${prefix}-historic-cash`, allocations: [{ revisionId: draft.id, lineId: paidLine.id, amount: "10" }], evidenceId: evidence.id, occurredAt: new Date("2026-10-01T00:00:00Z"), confirmedBy: account.id } });
    const assertHistorical = async () => {
      assert.deepEqual((await state()).expenses[0], historicalExpense);
      assert.deepEqual(await prisma.costFlowCash.findUniqueOrThrow({ where: { id: historicalCash.id } }), historicalCash);
      assert.equal((await prisma.costFlowEvidence.findUniqueOrThrow({ where: { id: evidence.id } })).sha256, evidence.sha256);
    };
    await assert.rejects(act("COPY_IC", { sourceRevisionId: draft.id, title: "Still pending" }), /đang xử lý/);
    await act("DECIDE", { requestId: draft.requestId, decision: "RETURN", reason: "Repair", correctionItems: "Update IC estimate" });
    assert.equal((await state()).revisions[0].effective, true);
    await act("COPY_IC", { sourceRevisionId: draft.id, title: "Successor", explanation: "Updated estimate after review" });
    const successor = (await state()).revisions.at(-1)!;
    assert.equal(successor.parentRevisionId, draft.id);
    assert.equal(successor.lines[0].id, draft.lines[0].id);
    assert.deepEqual((await prisma.workflowRequest.findUniqueOrThrow({ where: { id: sent.id } })).payload, sent.payload);
    await act("SUBMIT", { requestId: successor.requestId, explanation: "Updated budget after review" });
    assert.equal((await prisma.workflowRequest.findUniqueOrThrow({ where: { id: successor.requestId } })).currentStep, 0);
    await act("DECIDE", { requestId: successor.requestId, decision: "APPROVE" });
    await act("DECIDE", { requestId: successor.requestId, decision: "WITHDRAW", reason: "Fix" });
    assert.equal((await state()).revisions.find(r => r.id === successor.id)?.effective, false);
    assert.equal((await state()).revisions.some(r => r.effective), false);
    await assertHistorical();
    await act("COPY_IC", { sourceRevisionId: successor.id, title: "Transform", explanation: "Transform withdrawn revision with preserved lineage" });
    const transform = (await state()).revisions.at(-1)!;
    const sourceLine = transform.lines[0];
    await act("SPLIT_IC_LINE", { requestId: transform.requestId, lineIds: [sourceLine.id], lines: JSON.stringify([{ ...sourceLine, description: "Part A", quantity: "1" }, { ...sourceLine, description: "Part B", quantity: "2" }]) });
    const parts = (await state()).revisions.at(-1)!.lines;
    assert.equal(parts.length, 2);
    assert.ok(parts.every(l => l.id !== sourceLine.id && l.originLines?.[0].lineId === sourceLine.id));
    await assert.rejects(act("MERGE_IC_LINES", { requestId: transform.requestId, lineIds: [parts[0].id, "foreign"], lines: JSON.stringify([sourceLine]) }));
    await act("MERGE_IC_LINES", { requestId: transform.requestId, lineIds: parts.map(l => l.id), lines: JSON.stringify([{ ...sourceLine, description: "Merged", quantity: "3" }]) });
    const merged = (await state()).revisions.at(-1)!.lines[0];
    assert.equal(merged.originLines?.length, 2);
    assert.ok(!parts.some(l => l.id === merged.id));
    assert.equal((await state()).revisions[0].lines[0].id, sourceLine.id);
    await assertHistorical();
    await act("ADD_BRIEF", { title: "Quote source", sourceFileId: proof.id });
    const briefId = (await state()).briefs![0].id;
    const sale = { description: "Sale", unit: "set", quantity: "1", unitPrice: "999", vatPercent: "8", basis: "NET" };
    await act("SAVE_QUOTATION", { title: "BG1", customer: "Synthetic", briefIds: [briefId], lines: JSON.stringify([sale]) });
    const quote = (await state()).quotations!.at(-1)!;
    await act("SAVE_IC", { requestId: transform.requestId, title: "Quote override", briefIds: [briefId], lines: JSON.stringify([{ ...merged, quantity: "7", unit: "override", quotationId: quote.id, quotationLineId: quote.lines[0].id }]) });
    const beforeUpdate = structuredClone((await state()).revisions.at(-1)!);
    await act("SAVE_QUOTATION", { quotationId: quote.id, title: "BG2", customer: "Synthetic", briefIds: [briefId], lines: JSON.stringify([{ ...quote.lines[0], description: "New sale", quantity: "9", unit: "new unit", unitPrice: "5000" }]) });
    const quote2 = (await state()).quotations!.at(-1)!;
    assert.deepEqual((await state()).revisions.at(-1)!, beforeUpdate);
    await assert.rejects(act("APPLY_QUOTATION_LINES", { requestId: transform.requestId, quotationId: randomUUID(), quotationLineIds: [quote2.lines[0].id] }));
    await act("APPLY_QUOTATION_LINES", { requestId: transform.requestId, quotationId: quote2.id, quotationLineIds: [quote2.lines[0].id] });
    const imported = (await state()).revisions.at(-1)!.lines[0];
    assert.equal(imported.quantity, "7"); assert.equal(imported.unit, "override");
    assert.equal(imported.unitPrice, beforeUpdate.lines[0].unitPrice); assert.equal(imported.vatPercent, beforeUpdate.lines[0].vatPercent);
    assert.equal(imported.quotationId, quote2.id);
    await act("APPLY_QUOTATION_LINES", { requestId: transform.requestId, quotationId: quote2.id, quotationLineIds: [quote2.lines[0].id], updateQuantityIds: [quote2.lines[0].id], updateUnitIds: [quote2.lines[0].id] });
    assert.equal((await state()).revisions.at(-1)!.lines[0].quantity, "9");
    assert.equal((await state()).revisions.at(-1)!.lines[0].unit, "new unit");
    assert.deepEqual((await state()).quotations![0], quote);
    const activePo = currentPurchaseOrders((await state()).pos)[0];
    await act("REVISE_PO", { predecessorId: activePo.id, poNumber: activePo.number, net: "160", sourceFileId: proof.id, confirmed: "yes" });
    assert.equal(currentPurchaseOrders((await state()).pos)[0].net, "160");
    await assertHistorical();
    await act("SAVE_IC", { requestId: transform.requestId, title: "Removed newer line", lines: "[]" });
    assert.equal((await state()).revisions.at(-1)!.lines.length, 0);
    assert.deepEqual((await state()).expenses[0], historicalExpense);
    assert.equal((await state()).revisions[0].lines[0].id, historicalExpense.lineId);
    const frozenPayload = (await prisma.workflowRequest.findUniqueOrThrow({ where: { id: draft.requestId } })).payload;
    await act("IC_NOTES", { requestId: draft.requestId, notes: "Internal only" });
    assert.deepEqual((await prisma.workflowRequest.findUniqueOrThrow({ where: { id: draft.requestId } })).payload, frozenPayload);
    assert.equal((await prisma.project.findUniqueOrThrow({ where: { id: project.id } })).revenue, 777);
    await assertHistorical();
    assert.equal(await prisma.costFlowCash.count({ where: { projectId: project.id } }), 1);
  } finally {
    await prisma.costFlowCash.deleteMany({ where: { projectId: project.id } });
    await prisma.workflowNotificationDelivery.deleteMany({ where: { event: { request: { projectId: project.id } } } });
    await prisma.workflowApprovalEvent.deleteMany({ where: { request: { projectId: project.id } } });
    await prisma.workflowRequestReader.deleteMany({ where: { request: { projectId: project.id } } });
    await prisma.workflowDecision.deleteMany({ where: { request: { projectId: project.id } } });
    await prisma.workflowRequest.deleteMany({ where: { projectId: project.id } });
    await prisma.costFlowHistory.deleteMany({ where: { projectId: project.id } });
    await prisma.costFlowEvidence.deleteMany({ where: { projectId: project.id } });
    await prisma.costFlowWorkspace.deleteMany({ where: { projectId: project.id } });
    await prisma.project.deleteMany({ where: { id: { in: [project.id, other.id] } } });
    await prisma.user.deleteMany({ where: { id: { in: [account.id, reader.id] } } });
    await prisma.$disconnect();
  }
});
