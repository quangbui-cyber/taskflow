import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import type { FinanceData } from "../lib/costflow/types";

test("Brief/PO quotations preserve source and revisions, link IC with separate cost prices and enforce access", { skip: !process.env.COSTFLOW_TEST_DATABASE_URL }, async () => {
  const url = new URL(process.env.COSTFLOW_TEST_DATABASE_URL!);
  assert.ok(["localhost", "127.0.0.1"].includes(url.hostname) && url.pathname === "/costflow_test");
  process.env.DATABASE_URL = process.env.COSTFLOW_TEST_DATABASE_URL;
  const { prisma } = await import("../lib/prisma");
  const { executeFinance, loadFinance } = await import("../lib/costflow/service");
  const { getQuotationExport } = await import("../lib/costflow/quotationExport");
  const { emptyFinance } = await import("../lib/costflow/types");
  const { margin } = await import("../lib/costflow/reconciliation");
  const prefix = `quote-test-${randomUUID()}`;
  try {
    const account = await prisma.user.create({ data: { name: "Quotation Account", email: `${prefix}@example.test`, role: "ACCOUNT", passwordHash: "unused" } });
    const outsider = await prisma.user.create({ data: { name: "Outside Account", email: `${prefix}-outside@example.test`, role: "ACCOUNT", passwordHash: "unused" } });
    const reader = await prisma.user.create({ data: { name: "Project Reader", email: `${prefix}-reader@example.test`, role: "USER", passwordHash: "unused" } });
    const project = await prisma.project.create({ data: { name: "Quotation isolated integration", ownerId: account.id, revenue: 777, members: { create: [{ userId: account.id },{ userId: reader.id }] } } });
    const otherProject = await prisma.project.create({ data: { name: "Other quote project", ownerId: outsider.id, members: { create: { userId: outsider.id } } } });
    const brief = await prisma.projectFile.create({ data: { projectId: project.id, name: "brief.txt", mimeType: "text/plain", size: 14, data: Buffer.from("Original brief") } });
    const otherBrief = await prisma.projectFile.create({ data: { projectId: otherProject.id, name: "other.txt", mimeType: "text/plain", size: 5, data: Buffer.from("Other") } });
    const version = async () => (await prisma.costFlowWorkspace.findUnique({ where: { projectId: project.id } }))?.version ?? 0;
    const state = async () => (await prisma.costFlowWorkspace.findUniqueOrThrow({ where: { projectId: project.id } })).data as unknown as FinanceData;
    const act = async (actor: { id: string; role: string }, command: string, fields: Record<string,string | string[]> = {}, expected?: number) => {
      const form = new FormData(); form.set("command",command); if (command === "ADD_PO") form.set("confirmed", "yes");
      for (const [key,value] of Object.entries(fields)) for (const item of Array.isArray(value) ? value : [value]) form.append(key,item);
      return executeFinance(project.id, expected ?? await version(), actor, form, null);
    };
    // Simulate existing workspace JSON, without the newly added optional quotations collection.
    const legacy = emptyFinance(); delete legacy.quotations;
    await prisma.costFlowWorkspace.create({ data: { projectId: project.id, data: JSON.parse(JSON.stringify(legacy)) } });
    assert.equal((await loadFinance(project.id,account))?.data.quotations,undefined);
    const line = { description: "POSM item", unit: "cái", quantity: "3", unitPrice: "100.4", basis: "NET", vatPercent: "8" };
    const fields = { title: "Quotation test", customer: "Synthetic customer", sourceFileIds: brief.id, lines: JSON.stringify([line]) };
    await assert.rejects(() => act(outsider,"SAVE_QUOTATION",fields),/được phân công/);
    await assert.rejects(() => act(reader,"SAVE_QUOTATION",fields),/Chỉ Account/);
    await assert.rejects(() => act(account,"SAVE_QUOTATION",{...fields,sourceFileIds: otherBrief.id}),/đúng project/);

    await assert.rejects(() => act(account,"SAVE_QUOTATION",{...fields,lines: JSON.stringify([{...line,vatPercent:""}])}),/Nhập số hợp lệ/);
    await assert.rejects(() => act(account,"SAVE_QUOTATION",{...fields,lines:"[]"}),/1 đến 500/);
    const initial = await act(account,"SAVE_QUOTATION",fields);
    const quote = (await state()).quotations![0];
    assert.equal(initial.quotationId,quote.id);
    assert.equal(quote.lines[0].unitPrice,"100.4");
    assert.equal(quote.lines[0].cost.gross,"325");
    assert.equal((await state()).pos.length,0);
    assert.equal(margin(await state()).revenue,"0");
    assert.equal((await state()).revisions.length,0);
    assert.equal(await prisma.workflowRequest.count({where:{projectId:project.id}}),0);
    await assert.rejects(() => act(account,"SAVE_QUOTATION",fields,0),/đã thay đổi/);
    await prisma.projectFile.update({ where:{id:brief.id}, data:{data:Buffer.from("Changed brief")} });
    const evidence = await prisma.costFlowEvidence.findUniqueOrThrow({where:{id:quote.evidenceIds[0]}});
    assert.equal(Buffer.from(evidence.data).toString(),"Original brief");
    await act(account,"SAVE_QUOTATION",{ ...fields, quotationId:quote.id, sourceFileIds:[], evidenceIds:quote.evidenceIds, lines:JSON.stringify([{...line,unitPrice:"200"}]) });
    const revised = (await state()).quotations![1];
    assert.equal(revised.parentId,quote.id);
    assert.deepEqual((await state()).quotations![0],quote);
    assert.equal((await getQuotationExport(project.id,quote.id,account))?.quotation.lines[0].unitPrice,"100.4");
    assert.ok(await getQuotationExport(project.id,revised.id,reader));
    assert.equal(await getQuotationExport(project.id,quote.id,outsider),null);
    assert.equal(await getQuotationExport(otherProject.id,quote.id,outsider),null);
    const icLine = { ...line, unitPrice:"50.4", vatPercent:"0", quotationId:quote.id,quotationLineId:quote.lines[0].id, cost:{gross:"999999"} };
    await assert.rejects(() => act(account,"SAVE_IC",{title:"IC invalid",lines:JSON.stringify([{...icLine,quotationLineId:revised.lines[0].id}])}),/báo giá nguồn/);
    await act(account,"SAVE_IC",{title:"IC from quote",lines:JSON.stringify([icLine])});
    const ic = (await state()).revisions[0];
    assert.equal(ic.lines[0].unitPrice,"50.4");
    assert.ok(ic.lines[0].cost);
    assert.equal(ic.lines[0].cost.gross,"151");
    assert.equal(ic.lines[0].quotationId,quote.id);
    assert.equal(ic.lines[0].quotationLineId,quote.lines[0].id);
    assert.equal(ic.effective,false);
    assert.deepEqual(ic.evidenceIds, quote.evidenceIds);
    assert.equal((await getQuotationExport(project.id,quote.id,account))?.quotation.lines[0].unitPrice,"100.4");
    await assert.rejects(() => act(reader,"ADD_BRIEF",{title:"Denied Brief",sourceFileId:brief.id}),/Chỉ Account/);
    await assert.rejects(() => act(account,"ADD_BRIEF",{title:"Other Brief",sourceFileId:otherBrief.id}),/đúng project/);
    assert.equal((await state()).pos.length,0);
    await act(account,"ADD_BRIEF",{title:"Brief as project input",sourceFileId:brief.id});
    const registeredBrief = (await state()).briefs![0];
    await act(account,"SAVE_QUOTATION",{...fields,sourceFileIds:[],briefIds:[registeredBrief.id]});
    const briefQuote = (await state()).quotations!.at(-1)!;
    assert.deepEqual(briefQuote.poIds,[]);
    assert.deepEqual(briefQuote.briefIds,[registeredBrief.id]);
    await act(account,"SAVE_IC",{requestId:ic.requestId,title:"IC from Brief only",briefIds:[registeredBrief.id],lines:JSON.stringify([{...line,unitPrice:"30",quotationId:briefQuote.id,quotationLineId:briefQuote.lines[0].id}])});
    assert.deepEqual((await state()).revisions.at(-1)!.briefIds,[registeredBrief.id]);
    assert.deepEqual((await state()).revisions.at(-1)!.poIds,[]);
    await assert.rejects(() => act(account,"SAVE_QUOTATION",{...fields,briefIds:[randomUUID()]}),/Brief không thuộc/);
    await assert.rejects(() => act(account,"SAVE_IC",{requestId:ic.requestId,title:"Other Brief IC",briefIds:[randomUUID()],lines:JSON.stringify([line])}),/Brief không thuộc/);
    await act(account,"ADD_PO",{poNumber:"PO-quote-test",net:"1000",sourceFileId:brief.id});
    const po = (await state()).pos[0];
    await act(account,"SAVE_QUOTATION",{...fields,sourceFileIds:[],poIds:[po.id]});
    assert.deepEqual((await state()).quotations!.at(-1)!.poIds,[po.id]);
    assert.equal(margin(await state()).revenue,"1000");
    await assert.rejects(() => act(account,"SAVE_QUOTATION",{...fields,poIds:[randomUUID()]}),/PO không thuộc/);
    await assert.rejects(() => act(account,"SAVE_QUOTATION",{...fields,quotationId:randomUUID()}),/Báo giá nguồn/);
    await assert.rejects(() => act(account,"SAVE_QUOTATION",{...fields,evidenceIds:[randomUUID()]}),/Nguồn Brief/);
    await assert.rejects(() => act(account,"SAVE_IC",{requestId:ic.requestId,title:"IC wrong source",sourceFileIds:[otherBrief.id],lines:JSON.stringify([line])}),/đúng project/);
    await assert.rejects(() => act(account,"SAVE_IC",{requestId:ic.requestId,title:"IC wrong snapshot",evidenceIds:[randomUUID()],lines:JSON.stringify([line])}),/Nguồn tài liệu IC/);
    await act(account,"SAVE_IC",{requestId:ic.requestId,title:"IC from project documents",sourceFileIds:[brief.id],lines:JSON.stringify([line])});
    const documentIc = (await state()).revisions.find(r => r.id === ic.id)!;
    const documentEvidence = await prisma.costFlowEvidence.findUniqueOrThrow({where:{id:documentIc.evidenceIds!.at(-1)!}});
    assert.equal(documentEvidence.sourceFileId, brief.id);
    assert.equal(Buffer.from(documentEvidence.data).toString(), "Changed brief");
    await prisma.projectFile.update({where:{id:brief.id},data:{data:Buffer.from("Later project version")}});
    assert.equal(Buffer.from((await prisma.costFlowEvidence.findUniqueOrThrow({where:{id:documentEvidence.id}})).data).toString(), "Changed brief");
    const client = await prisma.client.create({data:{name:`${prefix}-client`}});
    await prisma.project.update({where:{id:project.id},data:{clientId:client.id}});
    const loaded = await loadFinance(project.id,account);
    assert.equal(loaded?.project.client?.id,client.id);
    assert.ok(loaded?.clients.some(item => item.id === client.id));
    assert.deepEqual((await loadFinance(project.id,outsider))?.clients ?? [],[]);
    await assert.rejects(() => act(account,"SAVE_QUOTATION",{...fields,sourceFileIds:[],clientId:randomUUID()}),/Khách hàng/);
    await act(account,"SAVE_QUOTATION",{...fields,sourceFileIds:[],clientId:client.id,customer:"Ignored client name"});
    const standalone = (await state()).quotations!.at(-1)!;
    assert.equal(standalone.customer,client.name);
    assert.deepEqual(standalone.evidenceIds,[]);
    assert.deepEqual(standalone.poIds,[]);
    assert.deepEqual(standalone.briefIds,[]);
    await act(account,"SAVE_QUOTATION",{...fields,sourceFileIds:[],quotationId:standalone.id,clientId:client.id});
    assert.deepEqual((await state()).quotations!.find(item => item.id === standalone.id),standalone);
    const snapshot = await state(); snapshot.closed=true;
    await prisma.costFlowWorkspace.update({where:{projectId:project.id},data:{data:JSON.parse(JSON.stringify(snapshot))}});
    await assert.rejects(() => act(account,"SAVE_QUOTATION",fields),/Tài chính đã đóng/);
    assert.equal((await prisma.project.findUniqueOrThrow({where:{id:project.id}})).revenue,777);
  } finally { await prisma.$disconnect(); }
});
