import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID, createHash } from "node:crypto";
import type { DocumentPayload } from "../lib/workflow/documents";
import { withPhase12TestSchema } from "./phase12/pilotFixture";

test("Workflow templates, independent/project documents, versions and signed originals obey server gates", { skip: !process.env.COSTFLOW_TEST_DATABASE_URL }, async () => {
  const url = new URL(process.env.COSTFLOW_TEST_DATABASE_URL!);
  assert.ok(["localhost", "127.0.0.1"].includes(url.hostname)); assert.equal(url.pathname, "/costflow_test");
  await withPhase12TestSchema(async () => {
  const { prisma } = await import("../lib/prisma");
  const { executeWorkflow, loadDocument, loadWorkflow, downloadWorkflowFile } = await import("../lib/workflow/service");
  const { assertWorkflowFile, isTemplateKind } = await import("../lib/workflow/documents");
  const prefix = `wf-test-${randomUUID()}`;
  const previousAttestationKey = process.env.DOCUMENT_ATTESTATION_KEY_V1;
  process.env.DOCUMENT_ATTESTATION_KEY_V1 = "workflow-integration-local-test-only-key";
  const mk = (label: string, role = "USER", managerId?: string) => prisma.user.create({ data: { name: `Workflow test ${label}`, email: `${prefix}-${label}@example.test`, passwordHash: "unused-in-service-test", role, managerId } });
  const proof = { name: "workflow-test.pdf", mimeType: "application/pdf", size: 23, data: new TextEncoder().encode("%PDF-1.4 test document\n") };
  const act = async (actor: { id: string; role: string }, command: string, fields: Record<string, string> = {}, upload?: typeof proof) => {
    const f = new FormData(); f.set("command", command); for (const [k, v] of Object.entries(fields)) f.set(k, v);
    if (command === "SUBMIT_DOCUMENT") f.set("signingMode", "PHYSICAL");
    return executeWorkflow(actor, f, command === "UPLOAD_SIGNED" ? null : upload ?? null, command === "UPLOAD_SIGNED" && upload ? [upload] : []);
  };
  try {
    const manager = await mk("manager"); const creator = await mk("creator", "USER", manager.id);
    const accountant = await mk("accountant"); const ceo = await mk("ceo"); const admin = await mk("admin", "ADMIN", manager.id);
    const owner = await mk("owner"); const stranger = await mk("stranger"); const member = await mk("member");
    assert.equal(isTemplateKind("__proto__"), false);
    assert.throws(() => assertWorkflowFile({ ...proof, size: 4 * 1024 * 1024 + 1 }), /4 MB/);
    assert.throws(() => assertWorkflowFile({ ...proof, mimeType: "text/html", name: "x.html" }), /Chỉ nhận/);
    const fields = { requirements: JSON.stringify({schemaVersion:1,requiredFields:["content"],requiredDocuments:[]}), changeNote:"Test revision", kind: "PROPOSAL", name: `Test proposal ${prefix}`, ownerId: owner.id, accountantId: accountant.id, ceoId: ceo.id, signerNames: "Test CEO", instructions: "Test only: kiểm tra đủ thông tin và tài liệu chính." };
    await assert.rejects(() => act(creator, "SAVE_TEMPLATE", fields, proof), /Admin/);
    const draftTemplateId = (await act(admin, "SAVE_TEMPLATE", { ...fields, ownerId: "" })).templateId!;
    const tpl = () => prisma.workflowTemplate.findUniqueOrThrow({ where: { id: draftTemplateId } });
    const templateAct = async (actor: typeof admin, command: string, extra: Record<string,string> = {}, upload?: typeof proof) => act(actor, command, { templateId: draftTemplateId, version: String((await tpl()).revision), ...extra }, upload);
    await assert.rejects(() => templateAct(admin, "PUBLISH_TEMPLATE"), /file mẫu thật|owner/);
    await templateAct(admin, "SAVE_TEMPLATE", fields, proof);
    await assert.rejects(() => templateAct(admin, "CONFIRM_TEMPLATE"), /Chỉ owner/);
    await templateAct(owner, "CONFIRM_TEMPLATE");
    await templateAct(admin, "SAVE_TEMPLATE", fields);
    assert.equal((await tpl()).ownerConfirmedAt, null);
    await assert.rejects(() => templateAct(admin, "PUBLISH_TEMPLATE"), /owner/);
    await templateAct(owner, "CONFIRM_TEMPLATE"); await templateAct(admin, "PUBLISH_TEMPLATE");
    await assert.rejects(() => templateAct(admin, "SAVE_TEMPLATE", fields), /giữ nguyên/);
    const originalTemplate = await tpl();
    assert.ok(await downloadWorkflowFile(originalTemplate.fileId!, creator));
    const newDraftId = (await act(admin, "SAVE_TEMPLATE", { ...fields, parentTemplateId: draftTemplateId })).templateId!;
    const newTpl = () => prisma.workflowTemplate.findUniqueOrThrow({ where: { id: newDraftId } });
    assert.equal((await newTpl()).ownerConfirmedAt, null);
    assert.equal((await newTpl()).fileId, originalTemplate.fileId);
    const docFields = { templateId: draftTemplateId, title: "Tờ trình thử độc lập", content: "Nội dung thử nghiệm", counterparty: "Test unit", amount: "100.4" };
    const draftId = (await act(creator, "SAVE_DOCUMENT", docFields)).requestId!;
    const req = (id = draftId) => prisma.workflowRequest.findUniqueOrThrow({ where: { id } });
    const requestFields = async (id: string, command: string): Promise<Record<string,string>> => {
      const current = await req(id);
      if (!["DECIDE_DOCUMENT", "TRANSFER_DOCUMENT"].includes(command)) return { requestId: id, version: String(current.version) };
      const submitted = await prisma.workflowApprovalEvent.findFirst({ where: { requestId: id, attemptId: current.currentAttemptId, action: "SUBMIT_DOCUMENT" }, orderBy: { createdAt: "desc" } });
      return { requestId: id, version: String(current.version), module: current.module, attemptId: current.currentAttemptId ?? "", stepIndex: String(current.currentStep), submittedVersion: String(submitted?.submittedVersion ?? "") };
    };
    const requestAct = async (actor: typeof creator, command: string, extra: Record<string,string> = {}, upload?: typeof proof, id = draftId) => act(actor, command, { ...await requestFields(id, command), ...extra }, upload);
    await assert.rejects(() => requestAct(creator, "SUBMIT_DOCUMENT"), /[Tt]ài liệu chính/);
    await requestAct(creator, "SAVE_DOCUMENT", docFields, proof);
    const primary = (await req()).payload as unknown as DocumentPayload;
    assert.equal(await loadDocument(draftId, stranger), null);
    assert.equal(await downloadWorkflowFile(primary.mainFileId, stranger), null);
    await requestAct(creator, "SUBMIT_DOCUMENT");
    await assert.rejects(() => requestAct(admin, "DECIDE_DOCUMENT", { decision: "APPROVE" }), /bước hiện tại/);
    await assert.rejects(() => requestAct(creator, "SAVE_DOCUMENT", docFields, proof), /bản đã gửi/);
    await requestAct(manager, "DECIDE_DOCUMENT", { decision: "APPROVE" });
    await assert.rejects(() => requestAct(accountant, "DECIDE_DOCUMENT", { decision: "APPROVE" }), /Kế toán cần xác nhận/);
    await requestAct(accountant, "DECIDE_DOCUMENT", { decision: "RETURN", reason: "Bổ sung nội dung", correctionItems: "Cập nhật nội dung theo góp ý" });
    const returnedState = await req();
    assert.equal(returnedState.state, "RETURNED");
    await act(owner, "CONFIRM_TEMPLATE", { templateId: newDraftId, version: String((await newTpl()).revision) });
    await act(admin, "PUBLISH_TEMPLATE", { templateId: newDraftId, version: String((await newTpl()).revision) });
    assert.equal(((await req()).payload as unknown as DocumentPayload).templateSnapshot!.version, originalTemplate.version);
    const newId = (await act(creator, "SAVE_DOCUMENT", { ...docFields, templateId: newDraftId, parentRequestId: draftId, title: "Tờ trình gửi lại", resubmissionResponse: "Đã cập nhật nội dung theo góp ý" }, proof)).requestId!;
    await requestAct(creator, "SUBMIT_DOCUMENT", {}, undefined, newId);
    assert.equal((await req(newId)).parentId, draftId);
    for (const actor of [manager, accountant, ceo]) await requestAct(actor, "DECIDE_DOCUMENT", { decision: "APPROVE", reviewConfirmed: "yes" }, undefined, newId);
    assert.equal((await req(newId)).state, "APPROVED");
    assert.equal(((await req(newId)).payload as unknown as DocumentPayload).signature, undefined);
    assert.equal(await prisma.workflowDecision.count({ where: { requestId: newId } }), 3);
    await assert.rejects(() => requestAct(creator, "UPLOAD_SIGNED", { keeper: "", location: "" }, proof, newId), /người giữ/);
    await requestAct(creator, "UPLOAD_SIGNED", { keeper: "Test keeper", location: "Test folder" }, proof, newId);
    assert.equal(((await req(newId)).payload as unknown as DocumentPayload).signature!.state, "PENDING");
    await assert.rejects(() => requestAct(admin, "CONFIRM_SIGNED", { signatureConfirmed: "yes" }, undefined, newId), /Quản lý phụ trách/);
    await requestAct(manager, "CONFIRM_SIGNED", { signatureConfirmed: "yes" }, undefined, newId);
    const confirmed = (await req(newId)).payload as unknown as DocumentPayload;
    assert.equal(confirmed.signature!.state, "CONFIRMED");
    const downloaded = await downloadWorkflowFile(confirmed.mainFileId, manager);
    assert.equal(downloaded!.sha256, createHash("sha256").update(proof.data).digest("hex"));
    await requestAct(creator, "ADD_REFERENCE", {}, proof, newId);
    assert.equal(((await req(newId)).payload as unknown as DocumentPayload).signature!.state, "CONFIRMED");
    await assert.rejects(() => act(creator, "SAVE_DOCUMENT", { ...docFields, templateId: newDraftId, parentRequestId: newId, title: "Sửa tài liệu sau duyệt" }, proof), /Tạo bản sửa đổi/);
    assert.equal((await req(newId)).state, "APPROVED");
    const project = await prisma.project.create({ data: { name: "Workflow membership test", ownerId: creator.id, members: { create: [creator, member].map(u => ({ userId: u.id })) } } });
    const projectDoc = (await act(creator, "SAVE_DOCUMENT", { ...docFields, templateId: newDraftId, projectId: project.id }, proof)).requestId!;
    assert.ok(await loadDocument(projectDoc, member)); assert.equal(await loadDocument(projectDoc, stranger), null);
    await assert.rejects(() => act(stranger, "SAVE_DOCUMENT", { ...docFields, templateId: newDraftId, projectId: project.id }, proof), /member/);
    assert.ok((await loadWorkflow(member)).requests.some(r => r.id === projectDoc));
    assert.ok(!(await loadWorkflow(stranger)).requests.some(r => r.id === newId));
    const noManager = await mk("missing-manager");
    const missing = (await act(noManager, "SAVE_DOCUMENT", { ...docFields, templateId: newDraftId }, proof)).requestId!;
    await assert.rejects(() => requestAct(noManager, "SUBMIT_DOCUMENT", {}, undefined, missing), /Thiếu người duyệt/);
    await requestAct(creator, "SUBMIT_DOCUMENT", {}, undefined, projectDoc);
    const concurrentFields = await requestFields(projectDoc, "DECIDE_DOCUMENT");
    const concurrent = await Promise.allSettled([0, 1].map(() => act(manager, "DECIDE_DOCUMENT", { ...concurrentFields, decision: "APPROVE" })));
    assert.equal(concurrent.filter(r => r.status === "fulfilled").length, 1);
    assert.equal(await prisma.workflowDecision.count({ where: { requestId: projectDoc } }), 1);
    await act(admin, "GRANT_APPROVAL_ROLE", { userId: stranger.id, approvalRole: "ACCOUNTANT" });
    await requestAct(manager, "TRANSFER_DOCUMENT", { assigneeId: stranger.id, reason: "Phân công ngoài project" }, undefined, projectDoc);
    assert.ok(await loadDocument(projectDoc, stranger));
    await assert.rejects(() => requestAct(accountant, "DECIDE_DOCUMENT", { decision: "APPROVE", reviewConfirmed: "yes" }, undefined, projectDoc), /bước hiện tại|không có quyền/);
    await requestAct(stranger, "DECIDE_DOCUMENT", { decision: "APPROVE", reviewConfirmed: "yes" }, undefined, projectDoc);
    await requestAct(ceo, "DECIDE_DOCUMENT", { decision: "REJECT", reason: "Test rejected" }, undefined, projectDoc);
    assert.equal((await req(projectDoc)).state, "REJECTED");
    await requestAct(manager, "TRANSFER_DOCUMENT", { target: "SIGNATURE", assigneeId: stranger.id, reason: "Giao kiểm tra bản ký" }, undefined, newId);
    await assert.rejects(() => requestAct(creator, "UPLOAD_SIGNED", { keeper: "Test keeper", location: "Test folder new scan" }, proof, newId), /Batch scan hiện tại/);
    assert.ok(await loadDocument(newId, stranger));
    assert.ok((await loadWorkflow(stranger)).requests.some(r => r.id === newId));
    await assert.rejects(() => requestAct(manager, "CONFIRM_SIGNED", { signatureConfirmed: "yes" }, undefined, newId), /Quản lý phụ trách/);
    await assert.rejects(() => requestAct(stranger, "CONFIRM_SIGNED", { signatureConfirmed: "yes" }, undefined, newId), /đang chờ kiểm tra/);
    assert.equal(await prisma.costFlowCash.count({ where: { requestId: newId } }), 0);
    assert.equal(await prisma.workflowHistory.count({ where: { requestId: newId } }), (await req(newId)).version + 1);
    // Each financial proposal has its own version stream. Both remain usable.
    assert.ok(isTemplateKind("PROPOSAL")); assert.ok(isTemplateKind("SERVICE_CONTRACT"));
    const cashBefore = await prisma.costFlowCash.findMany({ orderBy: { id: "asc" } });
    const budgetsBefore = await prisma.costFlowWorkspace.findMany({ orderBy: { projectId: "asc" } });
    const publish = async (kind: string, parentTemplateId?: string) => {
      const id = (await act(admin, "SAVE_TEMPLATE", { ...fields, kind, ownerId: admin.id, parentTemplateId: parentTemplateId ?? "" }, proof)).templateId!;
      const row = () => prisma.workflowTemplate.findUniqueOrThrow({ where: { id } });
      await act(admin, "CONFIRM_TEMPLATE", { templateId: id, version: String((await row()).revision) });
      await act(admin, "PUBLISH_TEMPLATE", { templateId: id, version: String((await row()).revision) });
      return row();
    };
    const advance = await publish("PROPOSAL_ADVANCE");
    const settlement = await publish("PROPOSAL_ADVANCE_SETTLEMENT");
    const createProposal = async (templateId: string) => (await act(creator, "SAVE_DOCUMENT", { ...docFields, templateId }, proof)).requestId!;
    const advanceRequest = await createProposal(advance.id);
    const settlementRequest = await createProposal(settlement.id);
    for (const id of [advanceRequest, settlementRequest]) await requestAct(creator, "SUBMIT_DOCUMENT", {}, undefined, id);
    const staleAdvance = await createProposal(advance.id);
    const currentSettlement = await createProposal(settlement.id);
    const advanceV2 = await publish("PROPOSAL_ADVANCE", advance.id);
    assert.equal(advanceV2.version, advance.version + 1);
    await assert.rejects(() => requestAct(creator, "SUBMIT_DOCUMENT", {}, undefined, staleAdvance), /phiên bản mới/);
    await requestAct(creator, "SUBMIT_DOCUMENT", {}, undefined, currentSettlement);
    assert.equal(((await req(advanceRequest)).payload as unknown as DocumentPayload).templateSnapshot!.version, advance.version);
    assert.equal(((await req(currentSettlement)).payload as unknown as DocumentPayload).templateSnapshot!.version, settlement.version);
    for (const id of [advanceRequest, settlementRequest]) {
      for (const actor of [manager, accountant, ceo]) await requestAct(actor, "DECIDE_DOCUMENT", { decision: "APPROVE", reviewConfirmed: "yes" }, undefined, id);
      assert.equal((await req(id)).state, "APPROVED");
      assert.equal(((await req(id)).payload as unknown as DocumentPayload).signature, undefined);
      assert.equal(await prisma.workflowDecision.count({ where: { requestId: id } }), 3);
    }
    assert.ok(!(await loadWorkflow(creator)).templates.some(t => t.id === originalTemplate.id));
    assert.ok(await loadDocument(draftId,creator));
    const legacyContract = await publish("SERVICE_CONTRACT");
    assert.ok((await loadWorkflow(creator)).templates.some(t => t.id === legacyContract.id));
    assert.deepEqual(await prisma.costFlowCash.findMany({ orderBy: { id: "asc" } }), cashBefore);
    assert.deepEqual(await prisma.costFlowWorkspace.findMany({ orderBy: { projectId: "asc" } }), budgetsBefore);
    console.log("Proposal variants PASS: simultaneous submission, independent freshness, frozen snapshots, legacy compatibility, Admin owner, no cash/budget effects");
    console.log("Workflow PASS: owner/publication gates, immutable versions/files, independent/member/assigned access, return/full resubmit, signature separation, no Admin approval bypass, concurrency, no cash side effect");
  } finally {
    if (previousAttestationKey === undefined) delete process.env.DOCUMENT_ATTESTATION_KEY_V1;
    else process.env.DOCUMENT_ATTESTATION_KEY_V1 = previousAttestationKey;
    await prisma.$disconnect();
  }
  });
});
